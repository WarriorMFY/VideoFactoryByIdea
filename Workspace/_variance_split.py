"""四张的方差分解：组内（同尺寸两张）vs 组间（跨尺寸）。只读分析。"""
DATA = {
    "脸宽%":      {"N": 94,   "P": 97,   "O": 93,   "Q": 90},
    "发际线%":    {"N": 7.0,  "P": 6.2,  "O": 4.6,  "Q": 12.7},
    "脸高/宽":    {"N": 1.27, "P": 1.23, "O": 1.31, "Q": 1.18},
    "上庭%":      {"N": 19,   "P": 21,   "O": 21,   "Q": 23},
    "中庭%":      {"N": 34,   "P": 34,   "O": 32,   "Q": 28},
    "下庭%":      {"N": 36,   "P": 35,   "O": 35,   "Q": 28},
    "眼裂":       {"N": 0.21, "P": 0.20, "O": 0.23, "Q": 0.22},
    "内眦距":     {"N": 0.24, "P": 0.23, "O": 0.18, "Q": 0.13},
    "鼻长":       {"N": 0.21, "P": 0.22, "O": 0.19, "Q": 0.19},
    "口宽":       {"N": 0.34, "P": 0.34, "O": 0.34, "Q": 0.35},
    "下巴高":     {"N": 0.17, "P": 0.15, "O": 0.21, "Q": 0.22},
}
REQ = {"脸宽%": 70, "发际线%": 0, "脸高/宽": 1.87, "上庭%": 33.3, "中庭%": 33.3, "下庭%": 33.3,
       "眼裂": 0.32, "内眦距": 0.36, "鼻长": 0.26, "口宽": 0.42, "下巴高": 0.12}
A, B = ["N", "P"], ["O", "Q"]

print(f"{'项':<9}{'组内均差':>9}{'组间均差':>9}{'倍数':>7}{'四张均值':>10}{'距卡值':>9}")
print("-" * 56)
ws, bs = [], []
for k, v in DATA.items():
    w = (abs(v["N"] - v["P"]) + abs(v["O"] - v["Q"])) / 2
    b = sum(abs(v[a] - v[x]) for a in A for x in B) / 4
    m = sum(v.values()) / 4
    ws.append(w)
    bs.append(b)
    ratio = b / w if w else float("nan")
    print(f"{k:<9}{w:>9.3f}{b:>9.3f}{ratio:>7.2f}{m:>10.2f}{m - REQ[k]:>9.2f}")

print("-" * 56)
print(f"{'均值':<9}{sum(ws)/len(ws):>9.3f}{sum(bs)/len(bs):>9.3f}"
      f"{sum(bs)/sum(ws):>7.2f}")
print(f"\n组内占总变异 ≈ {sum(ws)/(sum(ws)+sum(bs)):.0%} ；组间占 ≈ {sum(bs)/(sum(ws)+sum(bs)):.0%}")
print("\n【系统性偏离】四张全部落在同一侧且同向的项：")
for k, v in DATA.items():
    if all(x > REQ[k] for x in v.values()) or all(x < REQ[k] for x in v.values()):
        side = "全部偏大" if all(x > REQ[k] for x in v.values()) else "全部偏小"
        print(f"  {k:<9} 卡值 {REQ[k]:<6} 实际 {min(v.values()):.2f}~{max(v.values()):.2f}  {side}")
